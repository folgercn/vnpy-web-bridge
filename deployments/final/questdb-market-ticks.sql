-- Owned by the final-runtime deployment bootstrap, never by the worker.
CREATE TABLE IF NOT EXISTS market_ticks (
  ts TIMESTAMP,
  received_at TIMESTAMP,
  ingest_id STRING,
  ingest_seq LONG,
  schema_version INT,
  vt_symbol SYMBOL,
  symbol SYMBOL,
  exchange SYMBOL,
  gateway_name SYMBOL,
  name STRING,
  trading_day STRING,
  action_day STRING,
  last_price DOUBLE,
  last_volume DOUBLE,
  volume DOUBLE,
  turnover DOUBLE,
  open_interest DOUBLE,
  open_price DOUBLE,
  high_price DOUBLE,
  low_price DOUBLE,
  pre_close DOUBLE,
  limit_up DOUBLE,
  limit_down DOUBLE,
  bid_price_1 DOUBLE,
  bid_price_2 DOUBLE,
  bid_price_3 DOUBLE,
  bid_price_4 DOUBLE,
  bid_price_5 DOUBLE,
  ask_price_1 DOUBLE,
  ask_price_2 DOUBLE,
  ask_price_3 DOUBLE,
  ask_price_4 DOUBLE,
  ask_price_5 DOUBLE,
  bid_volume_1 DOUBLE,
  bid_volume_2 DOUBLE,
  bid_volume_3 DOUBLE,
  bid_volume_4 DOUBLE,
  bid_volume_5 DOUBLE,
  ask_volume_1 DOUBLE,
  ask_volume_2 DOUBLE,
  ask_volume_3 DOUBLE,
  ask_volume_4 DOUBLE,
  ask_volume_5 DOUBLE
) TIMESTAMP(ts) PARTITION BY DAY WAL DEDUP UPSERT KEYS(ts, ingest_id);
